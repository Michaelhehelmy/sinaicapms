# ═══════════════════════════════════════════════════════════
# MAIN
# ═══════════════════════════════════════════════════════════
MODE="${1:-setup}"

case "$MODE" in
  setup|first)
    full_setup
    ;;
  deploy)
    run_deploy "${@:2}"
    ;;
  test)
    load_env
    run_tests
    ;;
  e2e)
    run_e2e
    ;;
  status)
    show_status
    ;;
  --help|-h)
    echo "Usage: ./setup.sh [command]"
    echo ""
    echo "Commands:"
    echo "  (none)    Interactive setup — Cloudflare auth, install, test"
    echo "  deploy    Deploy to Cloudflare (production)"
    echo "  test      Run unit tests only"
    echo "  e2e       Run Playwright E2E tests"
    echo "  status    Show project & Cloudflare status"
    echo ""
    echo "Deploy options (passed to deploy.sh):"
    echo "  --backend    Backend only"
    echo "  --frontend   Frontend only"
    echo "  --migrate    Migrations only"
    echo "  --staging    Deploy to staging"
    ;;
  *)
    err "Unknown command: $MODE"
    echo "Run './setup.sh --help' for usage."
    exit 1
    ;;
esac
