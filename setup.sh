  info "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
  info "  Setup complete! Next steps:"
  info ""
  info "  Deploy to production:   ./setup.sh deploy"
  info "  Run E2E tests:          ./setup.sh e2e"
  info "  Check status:           ./setup.sh status"
  info ""
  info "  Total time: $(elapsed)"
  info "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
